BBOX = ((19.0, 190.5), (41.0, 77.8))


def _norm_lon(lon):
    if lon < -20.0:
        return lon + 360.0
    return lon


def _inside(poly, x, y):
    xs, ys = poly[:, 0], poly[:, 1]
    inside = False
    n = len(poly)
    j = n - 1
    for i in range(n):
        if (ys[i] > y) != (ys[j] > y):
            xint = (xs[j] - xs[i]) * (y - ys[i]) / (ys[j] - ys[i]) + xs[i]
            if x < xint:
                inside = not inside
        j = i
    return inside


def inside_russia(lat, lon):
    x = _norm_lon(float(lon))
    y = float(lat)
    if not (BBOX[0][0] - 0.3 <= x <= BBOX[0][1] + 0.3 and BBOX[1][0] - 0.3 <= y <= BBOX[1][1] + 0.3):
        return False
    return any(_inside(p, x, y) for p in POLYGONS)


